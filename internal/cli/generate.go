package cli

import (
	"fmt"
	"io"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/cobra/doc"
)

// manualAnnotation is the cobra annotation key holding a command's full
// manual text. It replaces Long in the man page, letting --help stay short.
const manualAnnotation = "bark/manual"

// addManPages adds man page support to cmd and its subcommands: a
// "Full manual: man <page>" line in --help, and a --generate flag that
// bypasses Args and RunE, so `bark add --generate man` works without args.
func addManPages(cmd *cobra.Command) {
	walkCommands(cmd, addManPage)
}

func addManPage(cmd *cobra.Command) {
	if _, ok := cmd.Annotations[manualAnnotation]; ok {
		cmd.Long += "\n\nFull manual: man " + manPageName(cmd)
		if cmd.HasAvailableSubCommands() {
			cmd.Long += "\nEach command has its own: man " + manPageName(cmd) + "-<command>"
		}
	}

	var kind string
	cmd.Flags().StringVar(&kind, "generate", "",
		`Generate docs: "man" prints this command's man page to stdout, "man-pages" writes pages for it and its subcommands to the current directory`)

	// A nil Args is left alone: on the root command it makes cobra reject
	// unknown subcommands, which a wrapper would silently disable.
	if validate := cmd.Args; validate != nil {
		cmd.Args = func(c *cobra.Command, args []string) error {
			if kind != "" {
				return nil
			}
			return validate(c, args)
		}
	}

	// Always set RunE, so commands without one (like root) are runnable and
	// can reach the --generate check; they show help otherwise.
	run := cmd.RunE
	cmd.RunE = func(c *cobra.Command, args []string) error {
		switch kind {
		case "":
			if run == nil {
				return c.Help()
			}
			return run(c, args)
		case "man":
			return generateMan(c, c.OutOrStdout())
		case "man-pages":
			return generateManPages(c, ".")
		default:
			return fmt.Errorf("unsupported --generate value %q (supported: man, man-pages)", kind)
		}
	}
}

// walkCommands calls fn on cmd and every command below it.
func walkCommands(cmd *cobra.Command, fn func(*cobra.Command)) {
	fn(cmd)
	for _, c := range cmd.Commands() {
		walkCommands(c, fn)
	}
}

// manPageName is the man page name for cmd, e.g. "bark-add".
func manPageName(cmd *cobra.Command) string {
	return strings.ReplaceAll(cmd.CommandPath(), " ", "-")
}

// generateMan writes the roff man page for cmd to w.
func generateMan(cmd *cobra.Command, w io.Writer) error {
	prepareForMan(cmd)
	return doc.GenMan(cmd, manHeader(cmd), w)
}

// generateManPages writes man pages for cmd and all its subcommands into dir,
// named like bark.1 and bark-add.1, so packaging never has to list commands.
func generateManPages(cmd *cobra.Command, dir string) error {
	// GenManTree has no per-page hook, so prepare the whole tree up front.
	walkCommands(cmd, prepareForMan)
	return doc.GenManTree(cmd, manHeader(cmd), dir)
}

// manHeader returns the .TH header fields for cmd's man pages. cobra takes
// the date from $SOURCE_DATE_EPOCH when set, for reproducible builds.
func manHeader(cmd *cobra.Command) *doc.GenManHeader {
	return &doc.GenManHeader{
		// Title is left empty so cobra derives it from the command path,
		// e.g. BARK or BARK-ADD.
		Section: "1",
		Source:  "bark " + cmd.Root().Version,
		Manual:  "User Commands",
	}
}

// prepareForMan adapts cmd's --help text for cobra's man page renderer.
// This mutates cmd, which is fine as the process exits after generating.
func prepareForMan(cmd *cobra.Command) {
	// Omit cobra's "Auto generated by spf13/cobra on <date>" footer.
	cmd.DisableAutoGenTag = true

	long := cmd.Long
	if manual, ok := cmd.Annotations[manualAnnotation]; ok {
		long = manual
	}

	// cobra feeds Long through a Markdown renderer, which drops <placeholders>
	// as HTML and reflows our hand-wrapped layout. Our text is written for
	// the terminal, so render it verbatim as a preformatted block instead.
	cmd.Long = preformatted(long)

	// The SYNOPSIS is built from Use, so escape its <placeholders> too.
	// Name() only reads Use's first word, so this doesn't rename the command.
	cmd.Use = strings.NewReplacer("<", `\<`, ">", `\>`).Replace(cmd.Use)
}

// preformatted turns s into a Markdown indented code block, so it is rendered
// exactly as written.
func preformatted(s string) string {
	lines := strings.Split(strings.TrimSpace(s), "\n")
	for i, line := range lines {
		if strings.TrimSpace(line) != "" {
			lines[i] = "    " + line
		}
	}
	return strings.Join(lines, "\n")
}
