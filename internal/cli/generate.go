package cli

import (
	"fmt"
	"io"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/cobra/doc"
)

// manualAnnotation is the cobra annotation key holding a command's full
// manual text. It replaces Long in the man page, letting --help stay short.
const manualAnnotation = "bark/manual"

// addGenerateFlag adds a --generate flag to cmd. When it is set, cmd skips its
// argument validation and normal RunE and prints the artifact instead, so
// e.g. `bark add --generate man` works without <repo> and <branch>.
func addGenerateFlag(cmd *cobra.Command, version string) {
	var kind string
	cmd.Flags().StringVar(&kind, "generate", "", `Print a generated artifact to stdout. Supported: "man"`)

	// A nil Args is left alone: on the root command it makes cobra reject
	// unknown subcommands, which a wrapper would silently disable.
	if validate := cmd.Args; validate != nil {
		cmd.Args = func(c *cobra.Command, args []string) error {
			if kind != "" {
				return nil
			}
			return validate(c, args)
		}
	}

	run := cmd.RunE
	cmd.RunE = func(c *cobra.Command, args []string) error {
		if kind != "" {
			return generateArtifact(c, kind, version, c.OutOrStdout())
		}
		if run == nil {
			return c.Help()
		}
		return run(c, args)
	}
}

// generateArtifact writes a generated artifact (currently only "man") for cmd to w,
// in the spirit of `rg --generate man`.
func generateArtifact(cmd *cobra.Command, kind, version string, w io.Writer) error {
	switch kind {
	case "man":
		return generateMan(cmd, version, w)
	default:
		return fmt.Errorf("unsupported --generate value %q (supported: man)", kind)
	}
}

// generateMan writes the roff man page for cmd to w.
// The date comes from $SOURCE_DATE_EPOCH if set, otherwise the current time.
func generateMan(cmd *cobra.Command, version string, w io.Writer) error {
	// Omit cobra's "Auto generated by spf13/cobra on <date>" footer.
	cmd.DisableAutoGenTag = true

	// The man page uses the full manual text when a command has one, falling
	// back to its --help Long text.
	long := cmd.Long
	if manual, ok := cmd.Annotations[manualAnnotation]; ok {
		long = manual
	}

	// cobra feeds Long through a Markdown renderer, which drops <placeholders>
	// as HTML and reflows our hand-wrapped layout. Our text is written for
	// the terminal, so render it verbatim as a preformatted block instead.
	// This mutates cmd, which is fine as the process exits after generating.
	cmd.Long = preformatted(long)

	// The SYNOPSIS is built from Use, so escape its <placeholders> too.
	// Name() only reads Use's first word, so this doesn't rename the command.
	cmd.Use = strings.NewReplacer("<", `\<`, ">", `\>`).Replace(cmd.Use)

	header := &doc.GenManHeader{
		// Title is left empty so cobra derives it from the command path,
		// e.g. BARK or BARK-ADD.
		Section: "1",
		Source:  "bark " + version,
		Manual:  "User Commands",
	}
	return doc.GenMan(cmd, header, w)
}

// preformatted turns s into a Markdown indented code block, so it is rendered
// exactly as written.
func preformatted(s string) string {
	lines := strings.Split(strings.TrimSpace(s), "\n")
	for i, line := range lines {
		if strings.TrimSpace(line) != "" {
			lines[i] = "    " + line
		}
	}
	return strings.Join(lines, "\n")
}
